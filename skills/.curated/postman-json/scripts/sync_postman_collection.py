def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def parse_js_string_literal(token: str) -> Optional[str]:
    token = token.strip()
    if len(token) < 2:
        return None
    quote = token[0]
    if quote not in {"'", '"', "`"} or token[-1] != quote:
        return None
    body = token[1:-1]
    if quote == "`" and "${" in body:
        return None
    if quote in {"'", '"'}:
        if quote == "'":
            body = body.replace("\\'", "'")
        if quote == '"':
            body = body.replace('\\"', '"')
        body = body.replace("\\/", "/")
        body = body.replace("\\\\", "\\")
    return body


def find_matching_paren(text: str, open_idx: int) -> Optional[int]:
    depth = 0
    state: Optional[str] = None
    escaped = False
    i = open_idx
    while i < len(text):
        ch = text[i]
        nxt = text[i + 1] if i + 1 < len(text) else ""

        if state == "line_comment":
            if ch == "\n":
                state = None
            i += 1
            continue
        if state == "block_comment":
            if ch == "*" and nxt == "/":
                state = None
                i += 2
                continue
            i += 1
            continue
        if state in {"single", "double", "template"}:
            if escaped:
                escaped = False
                i += 1
                continue
            if ch == "\\":
                escaped = True
                i += 1
                continue
            if (
                (state == "single" and ch == "'")
                or (state == "double" and ch == '"')
                or (state == "template" and ch == "`")
            ):
                state = None
            i += 1
            continue

        if ch == "/" and nxt == "/":
            state = "line_comment"
            i += 2
            continue
        if ch == "/" and nxt == "*":
            state = "block_comment"
            i += 2
            continue
        if ch == "'":
            state = "single"
            i += 1
            continue
        if ch == '"':
            state = "double"
            i += 1
            continue
        if ch == "`":
            state = "template"
            i += 1
            continue
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return None


