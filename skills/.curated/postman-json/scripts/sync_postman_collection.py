def extract_mounts(server_path: Path, server_text: str) -> List[Dict[str, Any]]:
    imports = parse_default_imports(server_path, server_text)
    mounts: List[Dict[str, Any]] = []
    seen: set[Tuple[str, Path, str]] = set()
    for app_name in extract_express_app_identifiers(server_text):
        for method, args, _start, _end in iter_object_calls(server_text, app_name, {"use"}):
            if method != "use":
                continue
            parts = split_top_level_commas(args)
            if not parts:
                continue
            mount_path = "/"
            callback_parts = parts
            if len(parts) >= 2:
                parsed_mount_path = parse_js_string_literal(parts[0])
                if parsed_mount_path is not None:
                    mount_path = parsed_mount_path or "/"
                    callback_parts = parts[1:]

            for callback_part in callback_parts:
                for callback_expr in extract_callback_expressions(callback_part):
                    callback_expr = callback_expr.strip()
                    if is_call_expression(callback_expr) and not parse_require_source(callback_expr):
                        continue
                    inline_source = parse_require_source(callback_expr)
                    router_name = None if inline_source else extract_identifier(callback_expr)
                    route_file: Optional[Path] = (
                        imports.get(router_name).source_path
                        if router_name and router_name in imports
                        else None
                    )

                    if not route_file and inline_source:
                        route_file = resolve_module_path(server_path, inline_source)
                        if route_file and not router_name:
                            try:
                                router_name = infer_exported_identifier(read_text(route_file))
                            except (OSError, UnicodeDecodeError):
                                router_name = None
                            if not router_name:
                                router_name = Path(inline_source).stem

                    if not route_file or not router_name:
                        continue

                    key = (mount_path, route_file, router_name)
                    if key in seen:
                        continue
                    seen.add(key)
                    mounts.append(
                        {
                            "router_name": router_name,
                            "mount_path": mount_path,
                            "route_file": route_file,
                        }
                    )
    return mounts


def find_matching_brace(text: str, open_idx: int) -> Optional[int]:
    depth = 0
    state: Optional[str] = None
    escaped = False
    i = open_idx
    while i < len(text):
        ch = text[i]
        nxt = text[i + 1] if i + 1 < len(text) else ""

        if state == "line_comment":
            if ch == "\n":
                state = None
            i += 1
            continue
        if state == "block_comment":
            if ch == "*" and nxt == "/":
                state = None
                i += 2
                continue
            i += 1
            continue
        if state in {"single", "double", "template"}:
            if escaped:
                escaped = False
                i += 1
                continue
            if ch == "\\":
                escaped = True
                i += 1
                continue
            if (
                (state == "single" and ch == "'")
                or (state == "double" and ch == '"')
                or (state == "template" and ch == "`")
            ):
                state = None
            i += 1
            continue

        if ch == "/" and nxt == "/":
            state = "line_comment"
            i += 2
            continue
        if ch == "/" and nxt == "*":
            state = "block_comment"
            i += 2
            continue
        if ch == "'":
            state = "single"
            i += 1
            continue
        if ch == '"':
            state = "double"
            i += 1
            continue
        if ch == "`":
            state = "template"
            i += 1
            continue
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return None


def find_statement_end(text: str, start_idx: int) -> int:
    paren = 0
    curly = 0
    square = 0
    state: Optional[str] = None
    escaped = False
    i = start_idx
    while i < len(text):
        ch = text[i]
        nxt = text[i + 1] if i + 1 < len(text) else ""

        if state == "line_comment":
            if ch == "\n":
                state = None
            i += 1
            continue
        if state == "block_comment":
            if ch == "*" and nxt == "/":
                state = None
                i += 2
                continue
            i += 1
            continue
        if state in {"single", "double", "template"}:
            if escaped:
                escaped = False
                i += 1
                continue
            if ch == "\\":
                escaped = True
                i += 1
                continue
            if (
                (state == "single" and ch == "'")
                or (state == "double" and ch == '"')
                or (state == "template" and ch == "`")
            ):
                state = None
            i += 1
            continue

        if ch == "/" and nxt == "/":
            state = "line_comment"
            i += 2
            continue
        if ch == "/" and nxt == "*":
            state = "block_comment"
            i += 2
            continue
        if ch == "'":
            state = "single"
            i += 1
            continue
        if ch == '"':
            state = "double"
            i += 1
            continue
        if ch == "`":
            state = "template"
            i += 1
            continue

        if ch == "(":
            paren += 1
        elif ch == ")":
            paren -= 1
        elif ch == "{":
            curly += 1
        elif ch == "}":
            curly -= 1
        elif ch == "[":
            square += 1
        elif ch == "]":
            square -= 1
        elif ch == ";" and paren == 0 and curly == 0 and square == 0:
            return i + 1
        i += 1
    return len(text)


def collect_exported_local_candidates(source_text: str, export_name: str) -> set[str]:
    candidates = {export_name}

    export_list_pattern = re.compile(r"""export\s*\{\s*([^}]+)\s*\}\s*;?""")
    for match in export_list_pattern.finditer(source_text):
        bindings = extract_named_binding_aliases(match.group(1))
        for alias, original in bindings.items():
            if alias == export_name:
                candidates.add(original)

    module_exports_pattern = re.compile(r"""module\.exports\s*=\s*\{""")
    for match in module_exports_pattern.finditer(source_text):
        open_brace = source_text.find("{", match.start())
        if open_brace == -1:
            continue
        close_brace = find_matching_brace(source_text, open_brace)
        if close_brace is None:
            continue
        for part in split_top_level_commas(source_text[open_brace + 1 : close_brace]):
            entry = part.strip()
            if not entry:
                continue
            if ":" in entry:
                left, right = entry.split(":", 1)
                key = parse_js_string_literal(left.strip()) or extract_identifier(left)
                value_identifier = extract_identifier(right)
                if key == export_name and value_identifier and value_identifier != "async":
                    candidates.add(value_identifier)
            else:
                shorthand = extract_identifier(entry)
                if shorthand == export_name:
                    candidates.add(shorthand)

    return candidates


def collect_scoped_source_for_symbol(source_text: str, export_name: str) -> Optional[str]:
    snippets: List[str] = []
    seen_spans: set[Tuple[int, int]] = set()
    seen_inline_snippets: set[str] = set()

    def append_span(start: int, end: int) -> None:
        if end <= start:
            return
        key = (start, end)
        if key in seen_spans:
            return
        seen_spans.add(key)
        snippets.append(source_text[start:end])

    def append_inline_snippet(snippet: str) -> None:
        normalized = snippet.strip()
        if not normalized or normalized in seen_inline_snippets:
            return
        seen_inline_snippets.add(normalized)
        snippets.append(normalized)

    def assignment_span_end(match_start: int, after_match_idx: int) -> int:
        end = find_statement_end(source_text, match_start)
        if end != len(source_text):
            return end
        # ASI-safe fallback when there is no trailing semicolon.
        open_brace = source_text.find("{", after_match_idx)
        if open_brace != -1:
            close_brace = find_matching_brace(source_text, open_brace)
            if close_brace is not None:
                return close_brace + 1
        return end

    symbols_to_scan: set[str]
    if export_name == "default":
        symbols_to_scan = set()
        for pattern in (
            re.compile(r"""export\s+default\b"""),
            re.compile(r"""module\.exports\s*="""),
            re.compile(r"""(?:module\.)?exports\.default\s*="""),
        ):
            for match in pattern.finditer(source_text):
                end = assignment_span_end(match.start(), match.end())
                append_span(match.start(), end)
                statement = source_text[match.start() : end]
                rhs = None
                export_default_match = re.search(
                    r"""export\s+default\s+(.+?)\s*;?\s*$""",
                    statement,
                    re.DOTALL,
                )
                if export_default_match:
                    rhs = export_default_match.group(1).strip()
                else:
                    assignment_rhs_match = re.search(r"""=\s*(.+?)\s*;?\s*$""", statement, re.DOTALL)
                    if assignment_rhs_match:
                        rhs = assignment_rhs_match.group(1).strip()
                if rhs:
                    identifier = extract_identifier(rhs)
                    if identifier:
                        symbols_to_scan.add(identifier)
    else:
        module_exports_pattern = re.compile(r"""module\.exports\s*=\s*\{""")
        for match in module_exports_pattern.finditer(source_text):
            open_brace = source_text.find("{", match.start())
            if open_brace == -1:
                continue
            close_brace = find_matching_brace(source_text, open_brace)
            if close_brace is None:
                continue
            object_body = source_text[open_brace + 1 : close_brace]
            for part in split_top_level_commas(object_body):
                entry = part.strip()
                if not entry or ":" not in entry:
                    continue
                left, right = entry.split(":", 1)
                key = parse_js_string_literal(left.strip()) or extract_identifier(left)
                if key == export_name:
                    append_inline_snippet(right)
        symbols_to_scan = collect_exported_local_candidates(source_text, export_name)

    for symbol in symbols_to_scan:
        function_pattern = re.compile(
            rf"""(?:export\s+)?(?:async\s+)?function\s+{re.escape(symbol)}\s*\("""
        )
        for match in function_pattern.finditer(source_text):
            param_open = match.end() - 1
            param_close = find_matching_paren(source_text, param_open)
            if param_close is None:
                continue
            open_brace = source_text.find("{", param_close + 1)
            if open_brace == -1:
                continue
            close_brace = find_matching_brace(source_text, open_brace)
            if close_brace is None:
                continue
            append_span(match.start(), close_brace + 1)

        for pattern in (
            re.compile(
                rf"""(?:export\s+)?(?:const|let|var)\s+{re.escape(symbol)}\s*="""
            ),
            re.compile(
                rf"""(?:module\.)?exports\.{re.escape(symbol)}\s*="""
            ),
            re.compile(
                rf"""module\.exports\s*\[\s*["']{re.escape(symbol)}["']\s*\]\s*="""
            ),
        ):
            for match in pattern.finditer(source_text):
                append_span(
                    match.start(),
                    assignment_span_end(match.start(), match.end()),
                )

    return "\n".join(snippets) if snippets else None


def analyze_source_requirements(source_text: str) -> Dict[str, Any]:
    return {
        "body_fields": extract_body_fields(source_text),
        "auth": bool(re.search(r"req\.headers\.authorization", source_text)),
        "needs_file": bool(re.search(r"\breq\.files?\b", source_text)),
        "upload_fields": extract_upload_fields(source_text),
    }


def build_endpoint_from_parts(
    *,
    method: str,
    route_path: str,
    middleware_parts: List[str],
    handler_source: str,
    mount_path: str,
    route_imports: Dict[str, ImportBinding],
    requirement_cache: Dict[Tuple[Path, Optional[str]], Dict[str, Any]],
    route_relative: str,
) -> Dict[str, Any]:
    middleware_names: List[str] = []
    for middleware_part in middleware_parts:
        for middleware_name in extract_identifiers_from_expr(middleware_part):
            if middleware_name not in middleware_names:
                middleware_names.append(middleware_name)
    route_scope_source = "\n".join([*middleware_parts, handler_source])

    body_fields = set(extract_body_fields(route_scope_source))
    upload_fields = set(extract_upload_fields(route_scope_source))
    auth_required = False
    needs_file = bool(re.search(r"\breq\.files?\b", route_scope_source))

    for middleware in middleware_names:
        lowered = middleware.lower()
        if "auth" in lowered:
            auth_required = True
        if "upload" in lowered:
            needs_file = True

        binding = route_imports.get(middleware)
        if not binding:
            continue
        source_path = binding.source_path
        imported_symbol = binding.imported_symbol
        if not source_path.exists():
            continue

        cache_key = (source_path, imported_symbol)
        if cache_key not in requirement_cache:
            try:
                source_text = read_text(source_path)
            except (OSError, UnicodeDecodeError) as exc:
                print(
                    f"Warning: cannot read middleware source {source_path}: {exc}",
                    file=sys.stderr,
                )
                continue

            if imported_symbol:
                scoped_source = collect_scoped_source_for_symbol(
                    source_text, imported_symbol
                )
                if scoped_source:
                    requirement_cache[cache_key] = analyze_source_requirements(
                        scoped_source
                    )
                else:
                    # If scoped extraction misses a valid export shape,
                    # fall back to file-level inference instead of dropping signals.
                    requirement_cache[cache_key] = analyze_source_requirements(source_text)
            else:
                requirement_cache[cache_key] = analyze_source_requirements(source_text)

        requirement = requirement_cache[cache_key]
        body_fields.update(requirement["body_fields"])
        upload_fields.update(requirement["upload_fields"])
        auth_required = auth_required or requirement["auth"]
        needs_file = needs_file or requirement["needs_file"]

    full_path = path_join(mount_path, route_path)
    return {
        "method": method.upper(),
        "path": full_path,
        "path_postman": to_postman_path(full_path),
        "route_file_relative": route_relative,
        "middleware_names": middleware_names,
        "body_fields": sorted(body_fields),
        "upload_fields": sorted(upload_fields),
        "needs_file": needs_file or bool(upload_fields),
        "auth_required": auth_required,
    }


def parse_route_endpoints(
    route_file: Path,
    mount_path: str,
    project_root: Path,
    requirement_cache: Dict[Tuple[Path, Optional[str]], Dict[str, Any]],
    mounted_router_name: Optional[str] = None,
) -> List[Dict[str, Any]]:
    try:
        route_text = read_text(route_file)
    except (OSError, UnicodeDecodeError) as exc:
        print(f"Warning: cannot read route file {route_file}: {exc}", file=sys.stderr)
        return []
    route_imports = parse_default_imports(route_file, route_text)
    try:
        route_relative = str(route_file.relative_to(project_root))
    except ValueError:
        route_relative = route_file.name
    endpoints: List[Dict[str, Any]] = []

    router_names: List[str]
    mounted_router_identifier = extract_identifier(mounted_router_name or "")
    if mounted_router_identifier:
        mounted_aliases = sorted(
            expand_identifier_aliases(route_text, {mounted_router_identifier})
        )
        has_endpoint_calls = False
        for alias in mounted_aliases:
            if any(iter_object_calls(route_text, alias, HTTP_METHODS)) or any(
                iter_router_route_calls(route_text, alias)
            ):
                has_endpoint_calls = True
                break

        # Common Express pattern: server imports route module as `usersRouter`,
        # but the module itself defines routes on `router`.
        if has_endpoint_calls:
            router_names = mounted_aliases
        else:
            router_names = extract_router_identifiers(route_text)
    else:
        router_names = extract_router_identifiers(route_text)
    if not router_names:
        print(
            f"Warning: no router identifiers detected in {route_file}",
            file=sys.stderr,
        )
        return []

    for router_name in router_names:
        for method, args, _start, _end in iter_object_calls(route_text, router_name, HTTP_METHODS):
            parts = split_top_level_commas(args)
            if len(parts) < 2:
                continue

            route_path = parse_js_string_literal(parts[0])
            if route_path is None:
                continue

            middleware_parts = parts[1:-1]
            handler_source = parts[-1]
            endpoints.append(
                build_endpoint_from_parts(
                    method=method,
                    route_path=route_path,
                    middleware_parts=middleware_parts,
                    handler_source=handler_source,
                    mount_path=mount_path,
                    route_imports=route_imports,
                    requirement_cache=requirement_cache,
                    route_relative=route_relative,
                )
            )
        for method, method_args, route_path in iter_router_route_calls(route_text, router_name):
            handler_parts = split_top_level_commas(method_args)
            if not handler_parts:
                continue

            middleware_parts = handler_parts[:-1]
            handler_source = handler_parts[-1]
            endpoints.append(
                build_endpoint_from_parts(
                    method=method,
                    route_path=route_path,
                    middleware_parts=middleware_parts,
                    handler_source=handler_source,
                    mount_path=mount_path,
                    route_imports=route_imports,
                    requirement_cache=requirement_cache,
                    route_relative=route_relative,
                )
            )

    return endpoints


def build_request(endpoint: Dict[str, Any]) -> Dict[str, Any]:
    path_segments = [segment for segment in endpoint["path_postman"].split("/") if segment]
    request: Dict[str, Any] = {
        "method": endpoint["method"],
        "url": {
            "raw": f"{{{{baseUrl}}}}{endpoint['path_postman']}",
            "host": ["{{baseUrl}}"],
            "path": path_segments,
        },
        "description": (
            f"{AUTO_GENERATED_TAG}\n"
            f"Endpoint: {endpoint['method']} {endpoint['path']}\n"
            f"Source: {endpoint['route_file_relative']}"
        ),
    }
    headers: List[Dict[str, str]] = []
    body_fields = set(endpoint["body_fields"])
    upload_fields = set(endpoint["upload_fields"])

    if endpoint["auth_required"]:
        request["auth"] = {
            "type": "bearer",
            "bearer": [{"key": "token", "value": "{{token}}", "type": "string"}],
        }

    if endpoint["needs_file"] or upload_fields:
        if not upload_fields:
            upload_fields.add("file")
        form_data: List[Dict[str, Any]] = []
        for upload_field in sorted(upload_fields):
            form_data.append(
                {"key": upload_field, "type": "file", "src": "", "description": "Attach a local file"}
            )
            body_fields.discard(upload_field)
        for body_field in sorted(body_fields):
            form_data.append(
                {
                    "key": body_field,
                    "value": str(infer_field_example(body_field)),
                    "type": "text",
                }
            )
        request["body"] = {"mode": "formdata", "formdata": form_data}
    elif body_fields:
        payload = {field: infer_field_example(field) for field in sorted(body_fields)}
        headers.append({"key": "Content-Type", "value": "application/json"})
        request["body"] = {
            "mode": "raw",
            "raw": json.dumps(payload, indent=2),
            "options": {"raw": {"language": "json"}},
        }

    if headers:
        request["header"] = headers
    return request


def ensure_folder(parent_items: List[Dict[str, Any]], folder_name: str) -> Dict[str, Any]:
    for item in parent_items:
        if item.get("name") == folder_name and isinstance(item.get("item"), list):
            return item
    new_folder = {"name": folder_name, "item": []}
    parent_items.append(new_folder)
    return new_folder


def build_generated_tree(endpoints: Sequence[Dict[str, Any]], root_name: str) -> Dict[str, Any]:
    root = {"name": root_name, "description": AUTO_GENERATED_TAG, "item": []}
    sorted_endpoints = sorted(
        endpoints, key=lambda entry: (entry["route_file_relative"], entry["path"], entry["method"])
    )
    for endpoint in sorted_endpoints:
        normalized_relative = str(endpoint["route_file_relative"]).replace("\\", "/")
        route_parts = Path(normalized_relative).with_suffix("").parts
        current = root
        for part in route_parts:
            current = ensure_folder(current["item"], part)
        current["item"].append(
            {
                "name": f"{endpoint['method']} {endpoint['path']}",
                "request": build_request(endpoint),
                "response": [],
            }
        )
    return root


def default_collection(collection_name: str) -> Dict[str, Any]:
    return {
        "info": {
            "name": collection_name,
            "schema": POSTMAN_SCHEMA,
        },
        "item": [],
        "variable": [],
    }


def load_collection(path: Path, collection_name: str) -> Dict[str, Any]:
    if not path.exists():
        return default_collection(collection_name)
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ValueError(f"Failed to parse existing collection JSON: {exc}") from exc
    if not isinstance(data, dict):
        raise ValueError("Existing collection JSON is not an object.")
    data.setdefault("info", {})
    data.setdefault("item", [])
    data.setdefault("variable", [])
    existing_schema = data.get("info", {}).get("schema", "")
    if existing_schema and existing_schema != POSTMAN_SCHEMA:
        print(
            f"Warning: existing collection uses schema {existing_schema!r}; upgrading to {POSTMAN_SCHEMA!r}. Verify manually.",
            file=sys.stderr,
        )
    if "name" not in data["info"]:
        data["info"]["name"] = collection_name
    if "schema" not in data["info"]:
        data["info"]["schema"] = POSTMAN_SCHEMA
    return data


def replace_generated_root(
    collection: Dict[str, Any], generated_root: Dict[str, Any], root_name: str
) -> None:
    items = collection.setdefault("item", [])
    kept: List[Dict[str, Any]] = []
    for item in items:
        if (
            item.get("name") == root_name
            and isinstance(item.get("item"), list)
            and AUTO_GENERATED_TAG in str(item.get("description", ""))
        ):
            continue
        kept.append(item)
    kept.append(generated_root)
    collection["item"] = kept


def parse_args(argv: Sequence[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate/update Postman collection JSON from Express routes."
    )
    parser.add_argument(
        "--project-root",
        "--backend-root",
        dest="project_root",
        default=".",
        help="Project root directory for path resolution",
    )
    parser.add_argument(
        "--server-file",
        default=None,
        help="Server entry file. When omitted, a best-effort discovery is used.",
    )
    parser.add_argument(
        "--output",
        default=None,
        help="Path for the Postman collection JSON. Defaults to ./postman/<project>.postman_collection.json",
    )
    parser.add_argument(
        "--collection-name",
        default=None,
        help="Postman collection name. Defaults to <Project Name> API",
    )
    parser.add_argument(
        "--base-url",
        default=None,
        help="Default baseUrl variable. When omitted, existing collection value is preserved.",
    )
    parser.add_argument(
        "--generated-root-name",
        default="source",
        help="Top-level generated folder name inside collection",
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str]) -> int:
    args = parse_args(argv)

    project_root = Path(args.project_root).resolve()
    server_file = discover_server_file(project_root, args.server_file)
    output_file = (
        resolve_path_from_root(project_root, args.output)
        if args.output
        else default_output_path(project_root)
    )
    collection_name = args.collection_name or default_collection_name(project_root)

    if not project_root.exists():
        print(f"Error: project root not found: {project_root}", file=sys.stderr)
        return 1
    if not server_file:
        print(
            "Error: unable to discover server file. Pass --server-file explicitly.",
            file=sys.stderr,
        )
        return 1
    if not server_file.exists():
        print(f"Error: server file not found: {server_file}", file=sys.stderr)
        return 1

    server_text = read_text(server_file)
    mounts = extract_mounts(server_file, server_text)
    if not mounts:
        print(
            "Error: no mounted routers discovered from <expressInstance>.use(...) in server file.",
            file=sys.stderr,
        )
        return 1

    requirement_cache: Dict[Tuple[Path, Optional[str]], Dict[str, Any]] = {}
    endpoints: List[Dict[str, Any]] = []
    for mount in mounts:
        route_file = mount["route_file"]
        if not route_file.exists():
            print(f"Warning: route file not found: {route_file}", file=sys.stderr)
            continue
        file_endpoints = parse_route_endpoints(
            route_file=route_file,
            mount_path=mount["mount_path"],
            project_root=project_root,
            requirement_cache=requirement_cache,
            mounted_router_name=mount.get("router_name"),
        )
        if not file_endpoints:
            print(
                f"Warning: no endpoints found in {route_file} (mounted at '{mount['mount_path']}'). Check router variable names.",
                file=sys.stderr,
            )
        endpoints.extend(file_endpoints)

    seen_endpoints: set[Tuple[str, str]] = set()
    deduped_endpoints: List[Dict[str, Any]] = []
    for endpoint in endpoints:
        key = (endpoint["method"], endpoint["path"])
        if key in seen_endpoints:
            print(
                (
                    "Warning: duplicate endpoint definition ignored: "
                    f"{endpoint['method']} {endpoint['path']} "
                    f"(source: {endpoint['route_file_relative']})"
                ),
                file=sys.stderr,
            )
            continue
        seen_endpoints.add(key)
        deduped_endpoints.append(endpoint)
    endpoints = deduped_endpoints

    if not endpoints:
        print("Error: no router endpoints discovered.", file=sys.stderr)
        return 1

    collection = load_collection(output_file, collection_name)
    if args.collection_name:
        collection["info"]["name"] = args.collection_name
    else:
        collection["info"].setdefault("name", collection_name)
    collection["info"]["schema"] = POSTMAN_SCHEMA

    base_url_value = args.base_url
    if base_url_value is None:
        base_url_value = get_variable_value(collection, "baseUrl") or "http://localhost:3000"

    ensure_variable(
        collection,
        "baseUrl",
        base_url_value,
        "Base URL for API requests, including protocol and port.",
        overwrite=args.base_url is not None,
    )

    generated_root = build_generated_tree(endpoints, args.generated_root_name)
    replace_generated_root(collection, generated_root, args.generated_root_name)
    referenced_variables = collect_referenced_variables(generated_root)
    for variable_name in sorted(referenced_variables):
        default_value, description = infer_variable_metadata(variable_name, base_url_value)
        ensure_variable(collection, variable_name, default_value, description)

    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(json.dumps(collection, indent=2) + "\n", encoding="utf-8")

    print(f"Synced Postman collection: {output_file}")
    print(f"Discovered endpoints: {len(endpoints)}")
    print(f"Generated root folder: {args.generated_root_name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
